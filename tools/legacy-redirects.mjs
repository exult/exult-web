/** Optional Apache redirects preserve existing PHP bookmarks without executing PHP. */
export function legacyRedirects(references) {
  const lines = ['# Generated by tools/build-site.mjs; no PHP handler is required.', 'DirectoryIndex index.html', 'ErrorDocument 404 /seventowers/404.html', '<IfModule mod_rewrite.c>', 'RewriteEngine On'];
  const rule = (file, conditions, target) => {
    for(const condition of conditions) lines.push(`RewriteCond %{QUERY_STRING} ${condition} [NC]`);
    // Explicit URL paths avoid Apache expanding relative targets against the hosting filesystem.
    lines.push(`RewriteRule ^${file}\\.php$ /seventowers/${target} [R=301,L,NE,QSD]`, '');
  };
  const parameter = (name,value,optional=false) => optional ? `^(?:(?!${name}=).)*$|(^|&)${name}=${value}(&|$)` : `(^|&)${name}=${value}(&|$)`;
  const downloads=[['exultmods','keyring','sifixes','avatarpack'],['usecode','tutorials','reference','highlighters'],['ultimaicons']];
  downloads.forEach((names,section)=>names.forEach((name,page)=>rule('downloads',[parameter('section',section,section===0),parameter('page',page,page===0)],name+'.html')));
  for(const name of ['exult_intrinsics','ucc_scripting','ucc_tutorial','ucc_reference']) {
    const condition=parameter('DATAFILE',`${name}\\.dat`,name==='exult_intrinsics');
    rule('code',[condition,parameter('OUTPUT','text')],`${name}.md`);
    rule('code',[condition,parameter('OUTPUT','naturaldocs')],`docs/${name}.naturaldocs.txt`);
    rule('code',[condition],name+'.html');
  }
  for(const [category,names] of Object.entries(references)) {
    const type=({intrinsics:5,scriptop:3,directives:6,reference:50})[category];
    for(const name of names) {
      const prefix=category==='intrinsics'?'(?:UI_)?':category==='directives'?'(?:%23)?':'';
      rule('ucc_ref',[parameter('TYPE',type,type===5),parameter('DATAFILE',prefix+name,category==='directives' && name==='line')],`reference-${category}-${name}.html`);
    }
  }
  rule('news',[parameter('showall','[^&]*')],'news-archive.html');
  for(const name of ['index','news','links','404']) rule(name,[],name+'.html');
  lines.push('</IfModule>','');
  return lines.join('\n');
}
